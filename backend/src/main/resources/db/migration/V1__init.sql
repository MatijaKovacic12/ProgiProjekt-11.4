
CREATE TABLE slika (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    putanja     VARCHAR(500) NOT NULL,
    alt_text    VARCHAR(255),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT ux_slika_putanja UNIQUE (putanja)
);


CREATE TABLE korisnik (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime           VARCHAR(100) NOT NULL,
    prezime       VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    display_name  VARCHAR(200),
    uloga         VARCHAR(20)  NOT NULL DEFAULT 'USER',
    id_slika      BIGINT REFERENCES slika(id) ON DELETE SET NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT chk_korisnik_uloga
        CHECK (uloga IN ('USER', 'ADMIN', 'ORGANIZER', 'GUIDE', 'MANAGER')),
    CONSTRAINT chk_korisnik_email
        CHECK (position('@' IN email) > 1)
);

CREATE UNIQUE INDEX ux_korisnik_email ON korisnik (lower(email));


CREATE TABLE korisnik_vanjski (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_korisnik       BIGINT       NOT NULL REFERENCES korisnik(id) ON DELETE CASCADE,
    provider          VARCHAR(30)  NOT NULL,  
    provider_user_id  VARCHAR(255) NOT NULL,   
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),


    CONSTRAINT ux_vanjski_provider_user UNIQUE (provider, provider_user_id),

    CONSTRAINT ux_vanjski_korisnik_provider UNIQUE (id_korisnik, provider)
);


CREATE TABLE kategorija (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime         VARCHAR(100) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX ux_kategorija_ime
    ON kategorija (lower(ime));
   

CREATE TABLE usluga (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ime         VARCHAR(150)  NOT NULL,
    opis        TEXT,
    cijena      NUMERIC(10,2) NOT NULL,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
   
    CONSTRAINT chk_usluga_cijena CHECK (cijena >= 0)
);

CREATE UNIQUE INDEX ux_usluga_ime
    ON usluga (lower(ime));




CREATE TABLE izlet (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv            VARCHAR(200)  NOT NULL,
    opis             TEXT          NOT NULL,
    id_kategorija    BIGINT        NOT NULL REFERENCES kategorija(id) ON DELETE RESTRICT,
    trajanje_minuta  INTEGER       NOT NULL,
    cijena           NUMERIC(10,2) NOT NULL, 
    max_sudionika    INTEGER       NOT NULL,
    broj_vodica      INTEGER       NOT NULL DEFAULT 1,
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_izlet_trajanje      CHECK (trajanje_minuta > 0),
    CONSTRAINT chk_izlet_cijena        CHECK (cijena >= 0),
    CONSTRAINT chk_izlet_max_sudionika CHECK (max_sudionika > 0),
    CONSTRAINT chk_izlet_broj_vodica   CHECK (broj_vodica >= 0)
);

CREATE INDEX ix_izlet_kategorija ON izlet (id_kategorija);

CREATE TABLE lokacija (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    naziv       VARCHAR(200)  NOT NULL,
    opis        VARCHAR(1000) NOT NULL,  
    znacaj      VARCHAR(1000),
    latitude    NUMERIC(9,6)  NOT NULL,  
    longitude   NUMERIC(9,6)  NOT NULL,   
    tip         VARCHAR(20)   NOT NULL DEFAULT 'LANDMARK',
    id_slika    BIGINT REFERENCES slika(id) ON DELETE SET NULL,
    id_izlet     BIGINT NOT NULL REFERENCES izlet(id)    ON DELETE CASCADE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_lokacija_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_lokacija_longitude CHECK (longitude BETWEEN -180 AND 180),
    CONSTRAINT chk_lokacija_tip       CHECK (tip IN ('LANDMARK', 'DEPARTURE', 'MAIN'))
);
CREATE UNIQUE INDEX ux_lokacija_jedna_glavna ON lokacija (id_izlet) WHERE tip = 'MAIN';




CREATE TABLE izlet_instanca (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_izlet        BIGINT      NOT NULL REFERENCES izlet(id) ON DELETE RESTRICT,
    termin_pocetak  TIMESTAMPTZ NOT NULL,
    termin_kraj     TIMESTAMPTZ NOT NULL, 
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT chk_termin_kraj CHECK (termin_kraj > termin_pocetak),
    CONSTRAINT ux_termin_izlet_pocetak UNIQUE (id_izlet, termin_pocetak)
);


CREATE INDEX ix_termin_pocetak ON izlet_instanca (termin_pocetak);

CREATE INDEX ix_termin_kraj    ON izlet_instanca (termin_kraj);


CREATE TABLE izlet_usluga (
    id_izlet   BIGINT NOT NULL REFERENCES izlet(id)  ON DELETE CASCADE,
    id_usluga  BIGINT NOT NULL REFERENCES usluga(id) ON DELETE RESTRICT,

    CONSTRAINT pk_izlet_usluga PRIMARY KEY (id_izlet, id_usluga)
);

CREATE INDEX ix_izlet_usluga_usluga ON izlet_usluga (id_usluga);

CREATE TABLE izlet_instanca_vodic (
    id_instanca  BIGINT      NOT NULL REFERENCES izlet_instanca(id) ON DELETE CASCADE,
    id_vodic     BIGINT      NOT NULL REFERENCES korisnik(id)       ON DELETE RESTRICT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT pk_izlet_instanca_vodic PRIMARY KEY (id_instanca, id_vodic)
);


CREATE TABLE rezervacija (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_korisnik    BIGINT        NOT NULL REFERENCES korisnik(id)       ON DELETE RESTRICT,
    id_instanca    BIGINT        NOT NULL REFERENCES izlet_instanca(id) ON DELETE RESTRICT,
    broj_osoba     INTEGER       NOT NULL,
    status         VARCHAR(20)   NOT NULL DEFAULT 'CONFIRMED',
    ukupna_cijena  NUMERIC(10,2) NOT NULL,  
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),  
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT chk_rezervacija_broj_osoba CHECK (broj_osoba > 0),
    CONSTRAINT chk_rezervacija_cijena     CHECK (ukupna_cijena >= 0),
    CONSTRAINT chk_rezervacija_status
        CHECK (status IN ('CONFIRMED', 'CANCELLED', 'COMPLETED'))
);


CREATE INDEX ix_rezervacija_korisnik ON rezervacija (id_korisnik, created_at DESC);

CREATE INDEX ix_rezervacija_instanca ON rezervacija (id_instanca, status);

CREATE INDEX ix_rezervacija_created  ON rezervacija (created_at);



CREATE TABLE rezervacija_usluga (
    id_rezervacija  BIGINT        NOT NULL REFERENCES rezervacija(id) ON DELETE CASCADE,
    id_usluga       BIGINT        NOT NULL REFERENCES usluga(id)      ON DELETE RESTRICT,
    kolicina        INTEGER       NOT NULL DEFAULT 1,
    cijena          NUMERIC(10,2) NOT NULL,  

    CONSTRAINT pk_rezervacija_usluga PRIMARY KEY (id_rezervacija, id_usluga),
    CONSTRAINT chk_rez_usluga_kolicina CHECK (kolicina > 0),
    CONSTRAINT chk_rez_usluga_cijena   CHECK (cijena >= 0)
);
